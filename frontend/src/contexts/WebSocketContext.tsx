// Fixed salt for verification code hashing (must match api.ts)
// Generated by scripts/generate_verification_salt.py
const VERIFICATION_SALT = new Uint8Array([
  0x31, 0xb5, 0x59, 0x86, 0xa7, 0x8f, 0x58, 0x8d,
  0x47, 0x66, 0xa5, 0x9b, 0x4c, 0xb6, 0xe3, 0x56
]);

function bytesToHex(bytes: Uint8Array): string {
  return Array.from(bytes).map(b => b.toString(16).padStart(2, '0')).join('');
}

